#!/usr/bin/env python3
"""Tileset switcher check: generate synthetic tileset packs, then let the shard client cycle them.

Everything is generated here (coloured squares with the tile id as a dot pattern), so the packs contain no
game art and may be shared freely. The client runs offline (no server) in `--tileset-check` mode, cycles
every pack on map 0 in each renderer, and reports PASS / FAIL (docs/SHARD_CORE.md "Tilesets").

    python tools/shard/tileset_check.py --project client -- --world world.json
    python tools/shard/tileset_check.py --project client --renderer 3d --shots OUT -- <game source flags>
    python tools/shard/tileset_check.py write DIR          # only write the synthetic packs (e.g. user://tilesets)

Packs written: synth-grid (16 px, identity), synth-hd (32 px, table mapping + a 2-frame animation, fallback
for the rest), synth-pad (14x16 px, "pad" fit, EGA palette snapping), plus two folders that must be refused
(bad-manifest: invalid id; no-manifest: no tileset.json). Needs $GODOT (or --godot); a display for --shots.
"""
from __future__ import annotations

import argparse
import colorsys
import json
import os
import shutil
import struct
import subprocess
import sys
import tempfile
import zlib
from pathlib import Path

SYNTH = ["synth-grid", "synth-hd", "synth-pad"]
REFUSED = ["bad-manifest", "no-manifest"]


def write_png(path: Path, w: int, h: int, px) -> None:
    """px(x, y) -> (r, g, b, a). Plain zlib PNG writer (no third-party modules)."""
    raw = bytearray()
    for y in range(h):
        raw.append(0)
        for x in range(w):
            raw.extend(px(x, y))
    def chunk(t: bytes, d: bytes) -> bytes:
        return struct.pack(">I", len(d)) + t + d + struct.pack(">I", zlib.crc32(t + d) & 0xFFFFFFFF)
    data = b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", w, h, 8, 6, 0, 0, 0))
    data += chunk(b"IDAT", zlib.compress(bytes(raw), 9)) + chunk(b"IEND", b"")
    path.write_bytes(data)


def tile_px(n: int, size: tuple[int, int], hue_shift: float = 0.0):
    """A tile: hue from n, dark border, n's 8 bits as a 4x2 dot pattern (readable at any size)."""
    tw, th = size
    r, g, b = colorsys.hsv_to_rgb(((n * 0.618) + hue_shift) % 1.0, 0.55, 0.95)
    bg = (int(r * 255), int(g * 255), int(b * 255), 255)
    def px(x: int, y: int):
        if x == 0 or y == 0 or x == tw - 1 or y == th - 1:
            return (20, 20, 30, 255)
        cx, cy = (x - 1) * 4 // max(1, tw - 2), (y - 1) * 2 // max(1, th - 2)
        bit = (n >> (cy * 4 + cx)) & 1
        inner = (x - 1) % max(1, (tw - 2) // 4) not in (0,) and (y - 1) % max(1, (th - 2) // 2) not in (0,)
        if bit and inner:
            return (250, 250, 250, 255)
        return bg
    return px


def sheet(path: Path, count: int, cols: int, size: tuple[int, int], hue_shift: float = 0.0) -> None:
    tw, th = size
    rows = (count + cols - 1) // cols
    tiles = [tile_px(n, size, hue_shift) for n in range(count)]
    def px(x: int, y: int):
        n = (y // th) * cols + x // tw
        return tiles[n](x % tw, y % th) if n < count else (0, 0, 0, 0)
    write_png(path, cols * tw, rows * th, px)


def write_packs(out: Path) -> None:
    out.mkdir(parents=True, exist_ok=True)
    common = {"schema": 1, "credit": "generated by tools/shard/tileset_check.py", "licence": "CC0-1.0",
              "platform": "community"}
    d = out / "synth-grid"; d.mkdir(exist_ok=True)
    sheet(d / "tiles.png", 256, 16, (16, 16))
    (d / "tileset.json").write_text(json.dumps({**common, "id": "synth-grid", "name": "Synthetic grid (16 px)",
        "tile_size": [16, 16], "source": {"kind": "pack", "sheets": [{"file": "tiles.png", "columns": 16}]},
        "mapping": {"kind": "identity"}}, indent=1))
    d = out / "synth-hd"; d.mkdir(exist_ok=True)
    sheet(d / "hd.png", 66, 8, (32, 32), hue_shift=0.33)
    (d / "tileset.json").write_text(json.dumps({**common, "id": "synth-hd", "name": "Synthetic HD (32 px, partial)",
        "tile_size": [32, 32], "source": {"kind": "pack", "sheets": [{"file": "hd.png", "columns": 8}]},
        "mapping": {"kind": "table", "table": {"0-63": 0, "64": [64, 65]}, "fps": 2},
        "voxel_colour": "sample"}, indent=1))
    d = out / "synth-pad"; d.mkdir(exist_ok=True)
    sheet(d / "narrow.png", 16, 16, (14, 16), hue_shift=0.66)
    (d / "tileset.json").write_text(json.dumps({**common, "id": "synth-pad", "name": "Synthetic 14x16 (pad, EGA)",
        "tile_size": [14, 16], "fit": "pad", "palette": "ega",
        "source": {"kind": "pack", "sheets": [{"file": "narrow.png", "columns": 16}]},
        "mapping": {"kind": "table", "table": {"0-15": 0}}}, indent=1))
    d = out / "bad-manifest"; d.mkdir(exist_ok=True)
    (d / "tileset.json").write_text(json.dumps({**common, "id": "Bad Pack!", "name": "", "tile_size": [2, 2],
        "source": {"kind": "pack", "sheets": [{"file": "../escape.png"}]}}))
    (out / "no-manifest").mkdir(exist_ok=True)


def run(args, extra: list[str]) -> int:
    godot = args.godot or os.environ.get("GODOT", "godot")
    tmp = None
    out = Path(args.dir) if args.dir else Path(tempfile.mkdtemp(prefix="tileset_check_"))
    if not args.dir:
        tmp = out
    write_packs(out)
    kinds = ["2d", "3d"] if args.renderer == "both" else [args.renderer]
    expect = ",".join(SYNTH + ([args.expect] if args.expect else []))
    ok = True
    for kind in kinds:
        cmd = [godot] + (["--headless"] if args.headless else []) + ["--path", args.project, "--",
            "--tileset-check", "--renderer", kind, "--tileset-dir", str(out.resolve()), "--tileset-expect", expect]
        if args.shots:
            cmd += ["--shots", args.shots]
        cmd += extra
        print("$ " + " ".join(cmd), flush=True)
        try:
            p = subprocess.run(cmd, capture_output=True, text=True, timeout=args.timeout)
            text = p.stdout + p.stderr
            code = p.returncode
        except subprocess.TimeoutExpired as e:
            text, code = (e.stdout or b"").decode() if isinstance(e.stdout, bytes) else (e.stdout or ""), -9
        lines = [l for l in text.splitlines() if l.startswith(("TILESET", "SCRIPT ERROR", "ERROR", "Parse Error"))]
        for l in lines:
            print("  " + l)
        problems = []
        if f"TILESET_CHECK PASS renderer={kind}" not in text or code != 0:
            problems.append(f"client check did not pass (exit {code})")
        for r in REFUSED:
            if f"TILESET skip dir={(out / r).resolve()}" not in text and f"TILESET skip dir={out.resolve()}/{r}" not in text:
                problems.append(f"{r} was not refused")
        if "SCRIPT ERROR" in text or "Parse Error" in text:
            problems.append("script errors")
        for pr in problems:
            print(f"  FAIL {kind}: {pr}")
        ok = ok and not problems
    if tmp and not args.keep:
        shutil.rmtree(tmp, ignore_errors=True)
    print("TILESET CHECK " + ("PASS" if ok else "FAIL"))
    return 0 if ok else 1


def main() -> int:
    argv = sys.argv[1:]
    extra: list[str] = []
    if "--" in argv:
        i = argv.index("--")
        argv, extra = argv[:i], argv[i + 1:]
    if argv[:1] == ["write"]:
        if len(argv) != 2:
            print("usage: tileset_check.py write DIR")
            return 2
        write_packs(Path(argv[1]))
        print(f"wrote {', '.join(SYNTH)} (+ refused {', '.join(REFUSED)}) to {argv[1]}")
        return 0
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--project", required=True, help="the Godot client folder")
    ap.add_argument("--godot")
    ap.add_argument("--renderer", choices=["2d", "3d", "both"], default="both")
    ap.add_argument("--shots", help="save one frame per pack (needs a display)")
    ap.add_argument("--dir", help="write the packs here (kept) instead of a temp folder")
    ap.add_argument("--expect", help="extra pack ids the game must offer (comma separated)")
    ap.add_argument("--headless", action="store_true", help="run Godot --headless (no frame comparison, no shots)")
    ap.add_argument("--keep", action="store_true")
    ap.add_argument("--timeout", type=int, default=240)
    return run(ap.parse_args(argv), extra)


if __name__ == "__main__":
    sys.exit(main())
