// Player reducers
// ---------------------------------------------------------------------------------------------

/// Enter the world in this region (first join). Players who arrive by handoff never call this.
#[reducer]
pub fn join(ctx: &ReducerContext, name: String) -> Result<(), String> {
    require_player_caller(ctx)?;
    if !valid_name(&name) {
        return Err("bad name".into());
    }
    let me = ctx.sender();
    if let Some(p) = ctx.db.player().identity().find(me) {
        if p.state != STATE_ACTIVE {
            return Err("handoff in progress".into());
        }
        ctx.db.player().identity().update(Player { name, ..p });
        return Ok(());
    }
    let cfg = config(ctx);
    let x = (cfg.x_min + cfg.x_max) / 2.0;
    ctx.db.player().insert(Player { identity: me, name, state: STATE_ACTIVE, online: true });
    ctx.db.player_input().insert(PlayerInput { identity: me, dir_x: 0, dir_y: 0 });
    put_transform(ctx, me, x, 0.0);
    ctx.db.departure().player().delete(me);
    report_entered(ctx, me);
    Ok(())
}

/// Movement intent: a direction on each axis, -1, 0 or 1. The tick moves the player.
#[reducer]
pub fn set_input(ctx: &ReducerContext, dir_x: i8, dir_y: i8) -> Result<(), String> {
    if !(-1..=1).contains(&dir_x) || !(-1..=1).contains(&dir_y) {
        return Err("direction must be -1, 0 or 1".into());
    }
    let me = ctx.sender();
    let p = ctx.db.player().identity().find(me).ok_or("join first")?;
    if p.state != STATE_ACTIVE {
        return Err("handoff in progress".into());
    }
    match ctx.db.player_input().identity().find(me) {
        Some(i) => { ctx.db.player_input().identity().update(PlayerInput { dir_x, dir_y, ..i }); }
        None => { ctx.db.player_input().insert(PlayerInput { identity: me, dir_x, dir_y }); }
    }
    Ok(())
}

// ---------------------------------------------------------------------------------------------
// Tick
// ---------------------------------------------------------------------------------------------

#[reducer]
pub fn tick(ctx: &ReducerContext, _row: TickSchedule) -> Result<(), String> {
    if ctx.sender() != ctx.database_identity() {
        return Err("tick is internal".into());
    }
    let cfg = config(ctx);
    let step = MAX_SPEED / TICK_HZ as f32;

    let movers: Vec<PlayerInput> = ctx.db.player_input().iter().filter(|i| i.dir_x != 0 || i.dir_y != 0).collect();
    for input in movers {
        let Some(p) = ctx.db.player().identity().find(input.identity) else { continue };
        if p.state != STATE_ACTIVE {
            continue;
        }
        let Some(t) = ctx.db.entity_transform().identity().find(input.identity) else { continue };
        let x = t.x + input.dir_x as f32 * step;
        let y = (t.y + input.dir_y as f32 * step).clamp(-WORLD_HALF_Y, WORLD_HALF_Y);

        if x >= cfg.x_min && x < cfg.x_max {
            put_transform(ctx, input.identity, x, y);
            continue;
        }
        // Crossing a border: hand off if a peer owns the destination, otherwise stop at the edge.
        match ctx.db.peer().iter().find(|peer| x >= peer.x_min && x < peer.x_max) {
            Some(peer) => start_handoff(ctx, &cfg, p, peer, x, y),
            None => {
                let edge = x.clamp(cfg.x_min, cfg.x_max - 0.001);
                put_transform(ctx, input.identity, edge, y);
            }
        }
    }

    let tick = cfg.tick + 1;
    if tick % HEARTBEAT_EVERY_TICKS == 0 {
        if let Some(g) = cfg.global_db {
            let population = ctx.db.player().iter().filter(|p| p.state == STATE_ACTIVE && p.online).count() as u32;
            ctx.db.heartbeat_outbox().insert(HeartbeatOutbox { msg_id: 0, target: global::Identity(g), region_id: cfg.region_id, population });
        }
    }
    ctx.db.region_config().id().update(RegionConfig { tick, ..cfg });
    Ok(())
}

/// Steps 1 and 2: lock the player here and offer them to the peer.
fn start_handoff(ctx: &ReducerContext, cfg: &RegionConfig, p: Player, peer: Peer, x: f32, y: f32) {
    let me = p.identity;
    let handoff_key = next_handoff_key(ctx, cfg.region_id);
    ctx.db.handoff_out().insert(HandoffOut { handoff_key, player: me, to_region: peer.region_id });
    if let Some(i) = ctx.db.player_input().identity().find(me) {
        ctx.db.player_input().identity().update(PlayerInput { dir_x: 0, dir_y: 0, ..i });
    }
    ctx.db.offer_handoff_outbox().insert(OfferHandoffOutbox {
        msg_id: 0,
        target: region::Identity(peer.db_identity),
        handoff_key,
        from_region: cfg.region_id,
        player: region::Identity(me),
        name: p.name.clone(),
        x,
        y,
    });
    ctx.db.player().identity().update(Player { state: STATE_LEAVING, ..p });
    log::info!("handoff {handoff_key}: offering player to region {}", peer.region_id);
}

// ---------------------------------------------------------------------------------------------
// IDC: handoff, target side
// ---------------------------------------------------------------------------------------------

/// Step 3 (runs in the TARGET region): accept a player. Idempotent per `handoff_key`.
#[reducer]
pub fn accept_handoff(ctx: &ReducerContext, handoff_key: u64, from_region: u32, player: Identity, name: String, x: f32, y: f32) -> Result<(), String> {
    require_peer(ctx, from_region)?;
    if ctx.db.handoff_in().handoff_key().find(handoff_key).is_some() {
        return Ok(());
    }
    let cfg = config(ctx);
    if !(x.is_finite() && y.is_finite()) || x < cfg.x_min || x >= cfg.x_max {
        return Err("position is not in this region".into());
    }
    if !valid_name(&name) {
        return Err("bad name".into());
    }
    if let Some(existing) = ctx.db.player().identity().find(player) {
        if existing.state != STATE_ARRIVING {
            return Err("player is already in this region".into());
        }
        ctx.db.player().identity().delete(player);
    }
    ctx.db.handoff_in().player().delete(player);
    ctx.db.player().insert(Player { identity: player, name, state: STATE_ARRIVING, online: false });
    ctx.db.handoff_in().insert(HandoffIn { handoff_key, player, from_region, x, y });
    Ok(())
}

/// Step 5 (runs in the TARGET region): the source has deleted its copy, so make the player playable.
#[reducer]
pub fn activate_handoff(ctx: &ReducerContext, handoff_key: u64, from_region: u32) -> Result<(), String> {
    require_peer(ctx, from_region)?;
    let Some(h) = ctx.db.handoff_in().handoff_key().find(handoff_key) else {
        return Ok(()); // already activated
    };
    if let Some(p) = ctx.db.player().identity().find(h.player) {
        ctx.db.player().identity().update(Player { state: STATE_ACTIVE, ..p });
    }
    match ctx.db.player_input().identity().find(h.player) {
        Some(i) => { ctx.db.player_input().identity().update(PlayerInput { dir_x: 0, dir_y: 0, ..i }); }
        None => { ctx.db.player_input().insert(PlayerInput { identity: h.player, dir_x: 0, dir_y: 0 }); }
    }
    put_transform(ctx, h.player, h.x, h.y);
    ctx.db.departure().player().delete(h.player);
    ctx.db.handoff_in().handoff_key().delete(handoff_key);
    report_entered(ctx, h.player);
    log::info!("handoff {handoff_key}: player active (from region {from_region})");
    Ok(())
}

// ---------------------------------------------------------------------------------------------
// IDC results (run in the SOURCE region; private; one call per outbox row)
// ---------------------------------------------------------------------------------------------

/// Step 4: Ok -> delete our copy and activate there. Err -> unlock the player here.
#[reducer(on_result(offer_handoff_outbox))]
pub fn on_offer_result(ctx: &ReducerContext, row: OfferHandoffOutbox, result: Result<(), String>) {
    let player = row.player.0;
    let Some(h) = ctx.db.handoff_out().handoff_key().find(row.handoff_key) else { return };
    ctx.db.handoff_out().handoff_key().delete(row.handoff_key);
    match result {
        Ok(()) => {
            ctx.db.player().identity().delete(player);
            ctx.db.player_input().identity().delete(player);
            ctx.db.entity_transform().identity().delete(player);
            ctx.db.departure().player().delete(player);
            ctx.db.departure().insert(Departure { player, to_region: h.to_region });
            ctx.db.activate_handoff_outbox().insert(ActivateHandoffOutbox {
                msg_id: 0,
                target: row.target,
                handoff_key: row.handoff_key,
                from_region: row.from_region,
            });
        }
        Err(e) => {
            log::warn!("handoff {}: rejected by region {}: {e}", row.handoff_key, h.to_region);
            if let Some(p) = ctx.db.player().identity().find(player) {
                ctx.db.player().identity().update(Player { state: STATE_ACTIVE, ..p });
            }
        }
    }
}

#[reducer(on_result(activate_handoff_outbox))]
pub fn on_activate_result(_ctx: &ReducerContext, row: ActivateHandoffOutbox, result: Result<(), String>) {
    if let Err(e) = result {
        // The player is gone here and stuck `Arriving` there. Alert an operator.
        log::error!("handoff {}: activation failed: {e}", row.handoff_key);
    }
}

#[reducer(on_result(heartbeat_outbox))]
pub fn on_heartbeat_result(_ctx: &ReducerContext, _row: HeartbeatOutbox, result: Result<(), String>) {
    if let Err(e) = result {
        log::warn!("heartbeat rejected by global: {e}");
    }
}

#[reducer(on_result(entered_outbox))]
pub fn on_entered_result(_ctx: &ReducerContext, _row: EnteredOutbox, result: Result<(), String>) {
    if let Err(e) = result {
        log::warn!("player_entered rejected by global: {e}");
    }
}
