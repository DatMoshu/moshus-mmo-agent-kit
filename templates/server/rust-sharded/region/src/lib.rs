#[reducer(init)]
pub fn init(ctx: &ReducerContext) {
    if ctx.db.region_config().id().find(0).is_none() {
        ctx.db.region_config().insert(RegionConfig {
            id: 0,
            admin: ctx.sender(),
            region_id: 0,
            x_min: -500.0,
            x_max: 500.0,
            global_db: None,
            tick: 0,
        });
    }
    if ctx.db.tick_schedule().iter().next().is_none() {
        ctx.db.tick_schedule().insert(TickSchedule {
            scheduled_id: 0,
            scheduled_at: ScheduleAt::Interval(TimeDuration::from_micros(1_000_000 / TICK_HZ as i64)),
        });
    }
}

/// Never reject peers or the global database here: the server runs this around every delivered IDC
/// call, and a rejected call is retried forever. Put player admission checks in player reducers.
#[reducer(client_connected)]
pub fn on_connect(ctx: &ReducerContext) -> Result<(), String> {
    if let Some(p) = ctx.db.player().identity().find(ctx.sender()) {
        ctx.db.player().identity().update(Player { online: true, ..p });
    }
    Ok(())
}

#[reducer(client_disconnected)]
pub fn on_disconnect(ctx: &ReducerContext) {
    if let Some(p) = ctx.db.player().identity().find(ctx.sender()) {
        ctx.db.player().identity().update(Player { online: false, ..p });
    }
    if let Some(i) = ctx.db.player_input().identity().find(ctx.sender()) {
        ctx.db.player_input().identity().update(PlayerInput { dir_x: 0, dir_y: 0, ..i });
    }
}

// ---------------------------------------------------------------------------------------------
// Admin reducers (operator, with `spacetime call`)
// ---------------------------------------------------------------------------------------------

/// Set this region's id, bounds and the global database identity.
#[reducer]
pub fn configure_region(ctx: &ReducerContext, region_id: u32, x_min: f32, x_max: f32, global_db: Identity) -> Result<(), String> {
    require_admin(ctx)?;
    if !(x_min.is_finite() && x_max.is_finite() && x_min < x_max) {
        return Err("bad bounds".into());
    }
    if region_id == 0 || region_id >= (1 << 23) {
        return Err("region_id must be 1..2^23".into());
    }
    let c = config(ctx);
    ctx.db.region_config().id().update(RegionConfig { region_id, x_min, x_max, global_db: Some(global_db), ..c });
    Ok(())
}

/// Add or update a neighbouring region (allow-list + routing).
#[reducer]
pub fn add_peer(ctx: &ReducerContext, region_id: u32, db_identity: Identity, x_min: f32, x_max: f32) -> Result<(), String> {
    require_admin(ctx)?;
    if !(x_min.is_finite() && x_max.is_finite() && x_min < x_max) {
        return Err("bad bounds".into());
    }
    if db_identity == ctx.database_identity() {
        return Err("a region cannot be its own peer".into());
    }
    let row = Peer { region_id, db_identity, x_min, x_max };
    if ctx.db.peer().region_id().find(region_id).is_some() {
        ctx.db.peer().region_id().update(row);
    } else {
        ctx.db.peer().insert(row);
    }
    Ok(())
}

/// Game-master teleport. Inside this region: move the player. Inside a peer region: start a
/// normal handoff (also the easiest way to test handoffs from the CLI, because `spacetime call`
/// disconnects after each call and a disconnect clears movement input).
#[reducer]
pub fn gm_teleport(ctx: &ReducerContext, player: Identity, x: f32, y: f32) -> Result<(), String> {
    require_admin(ctx)?;
    if !(x.is_finite() && y.is_finite()) {
        return Err("bad position".into());
    }
    let cfg = config(ctx);
    let p = ctx.db.player().identity().find(player).ok_or("no such player")?;
    if p.state != STATE_ACTIVE {
        return Err("handoff in progress".into());
    }
    let y = y.clamp(-WORLD_HALF_Y, WORLD_HALF_Y);
    if x >= cfg.x_min && x < cfg.x_max {
        put_transform(ctx, player, x, y);
        return Ok(());
    }
    let peer = ctx.db.peer().iter().find(|peer| x >= peer.x_min && x < peer.x_max).ok_or("no region owns that position")?;
    start_handoff(ctx, &cfg, p, peer, x, y);
    Ok(())
}

