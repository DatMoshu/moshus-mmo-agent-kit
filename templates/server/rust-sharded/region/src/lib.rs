//! Moshu's MMO Agent Kit: sharded world, REGION database (SpacetimeDB 2.14).
//!
//! Every region database runs this same module. Each one owns a vertical strip of the map,
//! x in [x_min, x_max). When a player walks across a border, the player is handed to the
//! neighbouring region with a five-step protocol over inter-database communication (IDC):
//!
//! 1. **lock**     source marks the player `Leaving` and freezes them (tick, here)
//! 2. **offer**    source inserts a row into `offer_handoff_outbox`, which calls
//!                 `accept_handoff` on the target region after this transaction commits
//! 3. **accept**   target validates and stores the player as `Arriving` (not yet playable)
//! 4. **delete**   source's `on_offer_result` sees Ok, deletes its copy, records a
//!                 `departure` (so the client knows where to reconnect), and sends `activate_handoff`
//! 5. **activate** target marks the player `Active`, spawns their transform and tells the global
//!                 database (`player_entered`)
//!
//! If the target rejects the offer, step 4 unlocks the player in the source instead. Each IDC call is
//! delivered exactly once and in order per outbox and target, so the player is never active in two
//! regions at once.
//!
//! IDC rules this module follows (see `rules/rust-module.md` R8, R23 and `skills/stdb-sharding-plan`):
//! - every IDC-called reducer checks `ctx.sender()` against the `peer` allow-list (or the global id)
//! - every IDC-called reducer is idempotent (keyed by `handoff_key`)
//! - `client_connected` never rejects a peer, because a rejected IDC call is retried forever
//! - every outbox has an `on_result` handler, so failures are logged and handled
//!
//! Receiver bindings live in `src/remote_bindings/` and are generated by `spacetime generate` from
//! `spacetime.json`. Never edit them. See this template's README for the regeneration order.

mod remote_bindings;

use remote_bindings::{global, region};
use spacetimedb::{
    reducer, table, view, Identity, ReducerContext, ScheduleAt, Table, TimeDuration, ViewContext,
};

pub const TICK_HZ: u32 = 20;
pub const MAX_SPEED: f32 = 8.0; // world units per second
pub const WORLD_HALF_Y: f32 = 500.0; // y is limited to [-WORLD_HALF_Y, WORLD_HALF_Y]
pub const CELL_SIZE: f32 = 50.0; // AOI cell edge
pub const HEARTBEAT_EVERY_TICKS: u64 = 100; // 5 s at 20 Hz
pub const NAME_MAX_CHARS: usize = 24;

/// Player lifecycle in this region.
pub const STATE_ACTIVE: u8 = 0;
pub const STATE_LEAVING: u8 = 1;
pub const STATE_ARRIVING: u8 = 2;

// ---------------------------------------------------------------------------------------------
// Tables
// ---------------------------------------------------------------------------------------------

/// Singleton (id = 0). Public so clients can read the region's bounds.
#[table(accessor = region_config, public)]
pub struct RegionConfig {
    #[primary_key]
    pub id: u8,
    pub admin: Identity,
    pub region_id: u32,
    pub x_min: f32,
    pub x_max: f32,
    /// The global database, once configured. Heartbeats and `player_entered` go there.
    pub global_db: Option<Identity>,
    pub tick: u64,
}

/// Neighbouring regions: the IDC allow-list and the routing table for handoffs. Private.
#[table(accessor = peer)]
pub struct Peer {
    #[primary_key]
    pub region_id: u32,
    #[unique]
    pub db_identity: Identity,
    pub x_min: f32,
    pub x_max: f32,
}

/// Cold player state. Private: clients read their own row through `my_player`.
#[table(accessor = player)]
pub struct Player {
    #[primary_key]
    pub identity: Identity,
    pub name: String,
    pub state: u8,
    pub online: bool,
}

/// Hot, public, AOI-indexed position. Only `Active` players have a row.
#[table(
    accessor = entity_transform,
    public,
    index(accessor = by_cell, btree(columns = [cell_x, cell_y]))
)]
pub struct EntityTransform {
    #[primary_key]
    pub identity: Identity,
    pub x: f32,
    pub y: f32,
    pub cell_x: i32,
    pub cell_y: i32,
}

/// Latest movement intent per player. Private.
#[table(accessor = player_input)]
pub struct PlayerInput {
    #[primary_key]
    pub identity: Identity,
    pub dir_x: i8,
    pub dir_y: i8,
}

/// Outgoing handoffs that are waiting for the target's answer.
#[table(accessor = handoff_out)]
pub struct HandoffOut {
    #[primary_key]
    pub handoff_key: u64,
    #[unique]
    pub player: Identity,
    pub to_region: u32,
}

/// Incoming handoffs that were accepted but not activated yet.
#[table(accessor = handoff_in)]
pub struct HandoffIn {
    #[primary_key]
    pub handoff_key: u64,
    #[unique]
    pub player: Identity,
    pub from_region: u32,
    pub x: f32,
    pub y: f32,
}

/// Where a player went. Read by the player through `my_departure`, then they reconnect there.
#[table(accessor = departure)]
pub struct Departure {
    #[primary_key]
    pub player: Identity,
    pub to_region: u32,
}

/// Local counter for handoff keys. A key is `(region_id << 40) | counter`, unique across regions.
#[table(accessor = handoff_counter)]
pub struct HandoffCounter {
    #[primary_key]
    pub id: u8,
    pub next: u64,
}

#[table(accessor = tick_schedule, scheduled(tick))]
pub struct TickSchedule {
    #[primary_key]
    #[auto_inc]
    pub scheduled_id: u64,
    pub scheduled_at: ScheduleAt,
}

// ---------------------------------------------------------------------------------------------
// IDC outboxes. One row = one reducer call in another database, sent after this transaction commits.
// ---------------------------------------------------------------------------------------------

/// Step 2: offer a player to a peer region (`region::accept_handoff`).
#[table(accessor = offer_handoff_outbox, outbox(region::accept_handoff))]
pub struct OfferHandoffOutbox {
    #[primary_key]
    #[auto_inc]
    pub msg_id: u64,
    #[target]
    pub target: region::Identity,
    pub handoff_key: u64,
    pub from_region: u32,
    pub player: region::Identity,
    pub name: String,
    pub x: f32,
    pub y: f32,
}

/// Step 4b: tell the target to activate the player (`region::activate_handoff`).
#[table(accessor = activate_handoff_outbox, outbox(region::activate_handoff))]
pub struct ActivateHandoffOutbox {
    #[primary_key]
    #[auto_inc]
    pub msg_id: u64,
    #[target]
    pub target: region::Identity,
    pub handoff_key: u64,
    pub from_region: u32,
}

/// Population report to the global database (`global::region_heartbeat`).
#[table(accessor = heartbeat_outbox, outbox(global::region_heartbeat))]
pub struct HeartbeatOutbox {
    #[primary_key]
    #[auto_inc]
    pub msg_id: u64,
    #[target]
    pub target: global::Identity,
    pub region_id: u32,
    pub population: u32,
}

/// "This player is now here", to the global database (`global::player_entered`).
#[table(accessor = entered_outbox, outbox(global::player_entered))]
pub struct EnteredOutbox {
    #[primary_key]
    #[auto_inc]
    pub msg_id: u64,
    #[target]
    pub target: global::Identity,
    pub region_id: u32,
    pub player: global::Identity,
    pub seq: u64,
}

// ---------------------------------------------------------------------------------------------
// Views
// ---------------------------------------------------------------------------------------------

#[view(accessor = my_player, public)]
fn my_player(ctx: &ViewContext) -> Option<Player> {
    ctx.db.player().identity().find(ctx.sender())
}

#[view(accessor = my_departure, public)]
fn my_departure(ctx: &ViewContext) -> Option<Departure> {
    ctx.db.departure().player().find(ctx.sender())
}

// ---------------------------------------------------------------------------------------------
// Helpers
// ---------------------------------------------------------------------------------------------

fn config(ctx: &ReducerContext) -> RegionConfig {
    ctx.db.region_config().id().find(0).expect("init creates region_config")
}

fn require_admin(ctx: &ReducerContext) -> Result<(), String> {
    if config(ctx).admin == ctx.sender() { Ok(()) } else { Err("admin only".into()) }
}

/// IDC allow-list: the caller must be the peer it claims to be.
fn require_peer(ctx: &ReducerContext, from_region: u32) -> Result<Peer, String> {
    let p = ctx.db.peer().db_identity().find(ctx.sender()).ok_or("caller is not a peer region")?;
    if p.region_id != from_region {
        return Err("from_region does not match the caller".into());
    }
    Ok(p)
}

/// Players must not be databases. Stops a peer (or the global db) from calling player reducers.
fn require_player_caller(ctx: &ReducerContext) -> Result<(), String> {
    let id = ctx.sender();
    if ctx.db.peer().db_identity().find(id).is_some() || config(ctx).global_db == Some(id) {
        return Err("databases cannot call player reducers".into());
    }
    Ok(())
}

fn cell_of(v: f32) -> i32 {
    (v / CELL_SIZE).floor() as i32
}

fn put_transform(ctx: &ReducerContext, identity: Identity, x: f32, y: f32) {
    let row = EntityTransform { identity, x, y, cell_x: cell_of(x), cell_y: cell_of(y) };
    if ctx.db.entity_transform().identity().find(identity).is_some() {
        ctx.db.entity_transform().identity().update(row);
    } else {
        ctx.db.entity_transform().insert(row);
    }
}

fn next_handoff_key(ctx: &ReducerContext, region_id: u32) -> u64 {
    let c = ctx.db.handoff_counter().id().find(0).unwrap_or(HandoffCounter { id: 0, next: 1 });
    let n = c.next;
    if ctx.db.handoff_counter().id().find(0).is_some() {
        ctx.db.handoff_counter().id().update(HandoffCounter { next: n + 1, ..c });
    } else {
        ctx.db.handoff_counter().insert(HandoffCounter { id: 0, next: n + 1 });
    }
    ((region_id as u64) << 40) | (n & ((1u64 << 40) - 1))
}

/// Tell the global database that `player` is active here. `seq` orders reports across regions.
fn report_entered(ctx: &ReducerContext, player: Identity) {
    let cfg = config(ctx);
    if let Some(g) = cfg.global_db {
        let seq = ctx.timestamp.to_micros_since_unix_epoch() as u64;
        ctx.db.entered_outbox().insert(EnteredOutbox {
            msg_id: 0,
            target: global::Identity(g),
            region_id: cfg.region_id,
            player: global::Identity(player),
            seq,
        });
    }
}

fn valid_name(name: &str) -> bool {
    let n = name.chars().count();
    n >= 1
        && n <= NAME_MAX_CHARS
        && name.chars().all(|c| c.is_alphanumeric() || c == ' ' || c == '_' || c == '-')
        && name.trim() == name
}

